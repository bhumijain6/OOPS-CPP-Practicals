
#include <iostream>
using namespace std;

int main() {
    int age = 19;
    float marks = 85.5;
    char grade = 'A';
    string name = "Student";
    const float PI = 3.14;

    cout << "Name: " << name << endl;
    cout << "Age: " << age << endl;
    cout << "Marks: " << marks << endl;
    cout << "Grade: " << grade << endl;
    cout << "PI: " << PI << endl;

    int a = 10, b = 5;

    cout << "Addition: " << a + b << endl;
    cout << "Subtraction: " << a - b << endl;
    cout << "Multiplication: " << a * b << endl;
    cout << "Division: " << a / b << endl;

    return 0;
}
